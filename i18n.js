function applyLanguage(language) {
  const messages = translations[language];
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (element instanceof HTMLMetaElement) {
      element.content = messages[key];
    } else {
      element.textContent = messages[key];
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", messages[element.dataset.i18nAriaLabel]);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", messages[element.dataset.i18nAlt]);
  });
}

const languageSelector = document.getElementById("language-selector");
const savedLanguage = localStorage.getItem("siteLanguage");
const initialLanguage = Object.prototype.hasOwnProperty.call(translations, savedLanguage) ? savedLanguage : "en";

languageSelector.value = initialLanguage;
applyLanguage(initialLanguage);

languageSelector.addEventListener("change", () => {
  localStorage.setItem("siteLanguage", languageSelector.value);
  applyLanguage(languageSelector.value);
});
