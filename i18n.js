function applyLanguage(language) {
  const messages = translations[language];
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (element instanceof HTMLMetaElement) {
      element.content = messages[key];
    } else {
      element.textContent = messages[key];
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", messages[element.dataset.i18nAriaLabel]);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", messages[element.dataset.i18nAlt]);
  });
}

const languageSelector = document.getElementById("language-selector");
const savedLanguage = localStorage.getItem("siteLanguage");
const browserLanguage = (navigator.language || "en").toLowerCase();
const detectedLanguage = browserLanguage === "tr" || browserLanguage.startsWith("tr-") ? "tr" : "en";
const initialLanguage = Object.prototype.hasOwnProperty.call(translations, savedLanguage) ? savedLanguage : detectedLanguage;

languageSelector.value = initialLanguage;
applyLanguage(initialLanguage);

languageSelector.addEventListener("change", () => {
  localStorage.setItem("siteLanguage", languageSelector.value);
  applyLanguage(languageSelector.value);
});

const menuToggle = document.querySelector(".menu-toggle");
const siteNavigation = document.getElementById("site-navigation");

if (menuToggle && siteNavigation) {
  const siteHeader = menuToggle.closest("header.site");
  const desktopNavigation = window.matchMedia("(min-width: 48rem)");
  siteHeader.classList.add("mobile-navigation-ready");

  const updateNavigationHeight = () => {
    if (menuToggle.getAttribute("aria-expanded") === "true") {
      siteNavigation.style.setProperty("--navigation-height", `${siteNavigation.scrollHeight + 16}px`);
    }
  };

  const setNavigationOpen = (isOpen) => {
    menuToggle.setAttribute("aria-expanded", String(isOpen));
    siteNavigation.classList.toggle("is-open", isOpen);
    siteNavigation.inert = !isOpen && !desktopNavigation.matches;

    if (isOpen) {
      updateNavigationHeight();
    }
  };

  setNavigationOpen(false);

  menuToggle.addEventListener("click", () => {
    setNavigationOpen(menuToggle.getAttribute("aria-expanded") !== "true");
  });

  siteNavigation.addEventListener("click", (event) => {
    if (event.target instanceof Element && event.target.closest("a")) {
      setNavigationOpen(false);
    }
  });

  languageSelector.addEventListener("change", updateNavigationHeight);
  window.addEventListener("resize", updateNavigationHeight);

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && menuToggle.getAttribute("aria-expanded") === "true") {
      setNavigationOpen(false);
      menuToggle.focus();
    }
  });

  desktopNavigation.addEventListener("change", (event) => {
    if (event.matches) {
      setNavigationOpen(false);
    } else {
      siteNavigation.inert = true;
    }
  });
}
